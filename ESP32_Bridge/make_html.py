# Packs ..\App\Lueftungssystem.html into app_html.h (gzip) for the ESP32.
import gzip, re, os
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, "..", "App", "Lueftungssystem.html"), encoding="utf8").read()
sec = open(os.path.join(here, "..", "App", "secrets.js"), encoding="utf8").read()
html = html.replace('<script src="secrets.js"></script>', "<script>" + sec + "</script>")   # key goes into the ESP copy only
html = re.sub(r'<link[^>]*fonts\.(googleapis|gstatic)\.com[^>]*>\s*', "", html)   # no internet on the ESP32 WiFi
gz = gzip.compress(html.encode("utf8"), 9)
rows = ",\n".join(", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20))
open(os.path.join(here, "app_html.h"), "w").write(
    f"// generated by make_html.py - do not edit\n#pragma once\n#include <Arduino.h>\n"
    f"const size_t APP_HTML_GZ_LEN = {len(gz)};\nconst uint8_t APP_HTML_GZ[] PROGMEM = {{\n{rows}\n}};\n")
print(f"app_html.h: {len(html)} bytes -> {len(gz)} bytes gzip")
